#!/usr/bin/env node
// Regenerate the runtime catalogue from ../data/exercises.json (+ filters.json).
// Main package gets a compact index (miniprogram/data/exercises.js).
// Description, steps and dataset media ids go to the exercise-detail subpackage
// (pages/exercise-detail/exercise-text.js) so the main package stays under 2MB.
// Fallbacks: exercises.sample.json, then scripts/placeholder-exercises.json.
// Usage: node scripts/build-data.js
const fs = require('fs'), path = require('path');
const codec = require('../utils/exercise-codec');
const root = path.resolve(__dirname, '..');
const dataDir = path.resolve(root, '../data');
const readJSON = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const exists = f => fs.existsSync(f);
const src = [path.join(dataDir, 'exercises.json'), path.join(dataDir, 'exercises.sample.json'), path.join(__dirname, 'placeholder-exercises.json')].find(exists);
const raw = readJSON(src);
const list = Array.isArray(raw) ? raw : (raw.exercises || []);
const arr = v => (Array.isArray(v) ? v.map(String) : v ? [String(v)] : []);
const str = v => (v == null ? '' : String(v));
const errors = [];
const out = list.map((e, i) => {
  const x = {
    id: str(e.id), nameZh: str(e.nameZh || e.name_zh), nameEn: str(e.nameEn || e.name_en),
    bodyPart: str(e.bodyPart), bodyPartDetail: str(e.bodyPartDetail),
    target: Array.isArray(e.target) ? str(e.target[0]) : str(e.target), secondary: arr(e.secondary),
    equipment: str(e.equipment), category: str(e.category || 'strength'), categoryZh: str(e.categoryZh),
    description: str(e.description), steps: arr(e.steps),
    translationPending: !!e.translationPending, untranslatedFields: arr(e.untranslatedFields),
  };
  if (e.illustration) x.illustration = str(e.illustration);
  if (e.video) x.video = str(e.video);
  if (e.poster) x.poster = str(e.poster);
  if (e.mediaId) x.mediaId = str(e.mediaId);
  if (!x.id || !x.nameZh || !x.bodyPart || !x.equipment) errors.push(`#${i} (${x.id}) missing required field`);
  if (!['chest', 'back', 'shoulders', 'legs', 'arms', 'core'].includes(x.bodyPart)) errors.push(x.id + ' bodyPart ' + x.bodyPart);
  return x;
});
const ids = new Set(); out.forEach(x => { if (ids.has(x.id)) errors.push('duplicate id ' + x.id); ids.add(x.id); });
const filtersFile = path.join(dataDir, 'filters.json');
let filters = exists(filtersFile) ? readJSON(filtersFile) : null;
if (filters) delete filters._note;
else {
  filters = {};
  ['bodyPart', 'equipment', 'target'].forEach(k => {
    const m = {}; out.forEach(x => { m[x[k]] = (m[x[k]] || 0) + 1; });
    filters[k] = Object.keys(m).map(v => ({ value: v, en: v, zh: v, count: m[v] }));
  });
}
if (filters) {
  for (const k of ['bodyPart', 'bodyPartDetail', 'equipment', 'category']) {
    (filters[k] || []).forEach(o => {
      const n = out.filter(e => e[k] === o.value).length;
      if (n !== o.count) errors.push('filters.' + k + ' ' + o.value + ' count ' + o.count + ' != ' + n);
    });
  }
  (filters.muscles || []).forEach(o => {
    const n = out.filter(e => e.target === o.value || (e.secondary || []).includes(o.value)).length;
    if (n !== o.count) errors.push('filters.muscles ' + o.value + ' count ' + o.count + ' != ' + n);
  });
}
const musclesFile = path.join(dataDir, 'muscles.json');
const muscles = exists(musclesFile) ? readJSON(musclesFile) : null;
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
let rows;
try { rows = out.map(codec.packRecord); }
catch (err) { console.error(err.message); process.exit(1); }
const placeholder = src.endsWith('placeholder-exercises.json');
const packed = {
  source: path.basename(src),
  placeholder,
  generatedFrom: { count: out.length, muscles: !!muscles, packed: true },
  rows,
  filters,
  muscles,
};
const body = `// AUTO-GENERATED by scripts/build-data.js from ${path.relative(path.resolve(root, '..'), src)} — do not edit.\n` +
  (placeholder ? '// PLACEHOLDER DATA — add data/exercises.json and re-run.\n' : '') +
  '// Compact index. description/steps are filled from pages/exercise-detail/exercise-text.js.\n' +
  `const codec = require('../utils/exercise-codec');\nmodule.exports = codec.expandPack(${JSON.stringify(packed)});\n`;
fs.writeFileSync(path.join(root, 'data/exercises.js'), body);
const text = {};
out.forEach(e => {
  const row = { d: e.description || '', s: e.steps || [] };
  if (e.mediaId) row.m = e.mediaId;
  text[e.id] = row;
});
const textFile = path.join(root, 'pages/exercise-detail/exercise-text.js');
fs.writeFileSync(textFile, `// AUTO-GENERATED by scripts/build-data.js — description, steps, dataset media id. Do not edit.\nmodule.exports = ${JSON.stringify(text)};\n`);
console.log(`wrote ${out.length} exercises from ${src}${muscles ? ' (+muscles.json)' : ''}`);
console.log('index', fs.statSync(path.join(root, 'data/exercises.js')).size, 'text', fs.statSync(textFile).size);
